const {serverNode}=require('./serverPresentation')
const assert = require('assert')
const fs = require('fs')
const vm = require('vm')
const page = fs.readFileSync('mdPackage/pages/archivedChat/index.js', 'utf8')
const renderSource = page.slice(page.indexOf('function renderMessage'), page.indexOf('\nPage('))
const context = {
  ...require('../static_utils/processTrace'),
  getMessageAttachments: require('../static_utils/chatAttachment').getMessageAttachments,
  normalizeCitations: require('../static_utils/chatSources').normalizeCitations,
  parseMarkdown: (text, type, options) => ({ text, type, options })
}
vm.createContext(context)
vm.runInContext(renderSource, context)
assert.strictEqual(context.renderMessage({ messageId: 'tool', role: 'tool' }), null)
assert.strictEqual(context.renderMessage({ messageId: 'a', role: 'assistant', content: '**hi**' }).article.text, '**hi**')
assert.strictEqual(context.renderMessage({ messageId: 'u', role: 'user', content: 'hello' }).article, null)
assert.strictEqual(context.renderMessage({ messageId: 'a', role: 'assistant', content: ' ' }).article, null)
const archivedRef = context.renderMessage({ messageId:'ref', role:'assistant', content:'引用[ref_11]', citations:[{ reference_id:11, url:'https://example.com/source' }] })
assert.strictEqual(archivedRef.article.options.citations[0].reference_id, 11)
assert.strictEqual(archivedRef.article.options.citations[0].url, 'https://example.com/source')
const toolMessage = context.renderMessage({ messageId: 'tool-reply', role: 'assistant', reasoningContent: 'reasoning', processTrace: [serverNode({ id: 'tool-1', kind: 'tool', title: 'Search', status: 'completed' })], processDurationMs: 1200, feedback: { value: 'like' } })
assert.strictEqual(toolMessage.thinking, true)
assert.strictEqual(toolMessage.thinkOpen, false)
assert.strictEqual(toolMessage.processTrace.length, 1)
assert.strictEqual(toolMessage.feedback.value, 'like')
const template = fs.readFileSync('mdPackage/pages/archivedChat/index.wxml', 'utf8')
assert.match(template, /<think-item[\s\S]*?bind:open="openReasoning"/)
assert.match(template, /<assis-act[^>]*bind:openSources="openSources"/)
assert.match(template, /<assis-act compact="{{true}}" bind:copy="copyMessage"/)
const actionTemplate = fs.readFileSync('mdPackage/components/assisAct/index.wxml', 'utf8')
assert.match(actionTemplate, /<block wx:if="{{!compact && !\(item\.status === 'failed' && !item\.messageId\)}}">[\s\S]*icon-share(?:'\}\})? message-action-icon[\s\S]*id="moreFlyout"[\s\S]*<\/block>/)
assert.match(actionTemplate, /wx:if="{{citations.length && !\(item\.status === 'failed' && !item\.messageId\)}}"/)
assert.match(actionTemplate, /bind:tap="retryLocal"/)
assert.doesNotMatch(actionTemplate, /<text wx:if="\{\{item\.turnId\}\}" class="iconfont icon-refresh/)
const router = fs.readFileSync('static_router/settingRouter.js', 'utf8')
assert.match(router, /routeOptions\.stacked === true \? \{[\s\S]*?popGestureDirection: 'multi'/)
const start = router.indexOf('  const handlePreviousPageAnimation = ')
const end = router.indexOf('\n\n  return {', start)
const animation = new Function('primaryAnimation', 'curvePrimaryAnimation', 'userGestureInProgress', router.slice(start, end) + '\nreturn handlePreviousPageAnimation')
const progress = { value: 1 }
const style = animation(progress, progress, { value: false })
assert.strictEqual(style().transform, 'translateY(-12px) scale(0.96)')
progress.value = 0
assert.strictEqual(style().transform, 'translateY(0px) scale(1)')
console.log('archivedChatView: readonly message rendering and stacked route endpoints passed')
